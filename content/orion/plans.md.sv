### Byggminuter och plannivåer: En grov guide

*En rimlig high-end uppskattning för den genomsnittliga byggtiden per bekräftelse är 10 sekunder.*

- Professionella med mindre än 20 åtaganden per dag bör vara bra med de 100 byggminuter som ingår i planen.

- Företag med mindre än 100 åtaganden per dag bör vara bra med de 500 byggminuter som ingår i planen.

- Företag med mindre än 500 åtaganden per dag bör klara sig bra med de 2500 byggminuter som ingår i planen.

