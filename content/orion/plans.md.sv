### Fotnoter

1. Lagringsutnyttjande beräknas baserat på storleken på fyra utcheckningar av arbetskopior för varje plats: två källträd och två resulterande byggträd.

2. Lagringsutnyttjande beräknas baserat på den totala storleken på SunStar Systems-baserade Subversion-datalager för företagskunder, inte enskilda kassor, vilket är ett *jämförande mindre nummer* (ungefär storleken på en enskild kassabetalning från ett källträd).

3. SLA täcker webbplats tillgångar * och * Orion online IDE * och * bygga system tillgänglighet, men utesluter Subversion version kontrollsystem, som vi förväntar oss att förbli konkurrenskraftiga med GitHub allmänna tillgänglighetsmått.

