VDIO var en systerplats för RDIO (nu defunct också) tillägnad att erbjuda online streaming video &mdash; i form av premium, nyligen släppt blockbuster filmer &mdash; till sina blivande kunder.  Mitt engagemang i den uppstarten sträckte sig över en sexmånadersperiod i slutet av 2011 - början av 2012.  Min huvudsakliga uppgift var att utveckla ett manus för att främja en `postgreskv` slav till en mästare över kontinenter, efter solen. Andra uppgifter involverade dokumentering och främjande av interna verktyg för deras `utvecklare`

VDIO övergavs så småningom i mars 2012 av sina grundare och viks in i RDIO, som tillhandahöll all finansiering för start.
