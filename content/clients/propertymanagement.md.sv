Mitt arbete inom detta område spänner över åren 2000-2006 som mjukvaruutvecklare och webbansvarig.
skrev en CMS-liknande tjänst för att vara värd för community-webbplatser som erbjuds av local Property
förvaltningsbolag.  Det integreras med Tops programvara för att tillhandahålla online-redovisning
data för fastighetsägare, liksom olika forum för samhällsmedlemmar att kommunicera
med varandra.  Vid sin topp var vi värd över 100 platser.  Tekniken är baserad
på `Linux`, `mod_perl`, `httpd`och `msyql`- typiska LAMP-stack grejer.  Den enda romanen
Pjäsen var att förvara `SQL` satser i själva databasen, för att borra ned sekventiellt
till enskilda poster utan hårdkodning `SQL`