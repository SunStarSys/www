    <p>
      Loggvyn visar revisionshistoriken för den valda källan
      fil eller katalog. För varje revidering är följande information
      displayed:

<ul>
        <li>Revisionsnumret. I Subversion-datalager är detta en
            länk till <a href="help_rootview.html#view-rev">revision
            visa</a></li>
        <li>För filer, länkar till
        <a href="help_rootview.html#view-markup">visa</a>,
        <a href="help_rootview.html#view-checkout">hämta</a>och
        <a href="help_rootview.html#view-annotate">kommentera</a> den
          revidering. För kataloger, en länk till
        <a href="help_dirview.html">listkataloginnehåll</a></li>
        <li>En länk för att välja revidering för diff. (se nedan)</li>
        <li>Datum och ålder för ändringen</li>
        <li>Författaren till ändringen</li>
        <li>CVS-grenen (vanligtvis <em>HUVUD</em>, om inte på en gren)</li>
        <li>Eventuellt en lista över CVS-taggar som är bundna till revisionen (om någon)</li>
        <li>Storleken på ändringen mätt i tillagda och borttagna rader i
            kod. (endast CVS)</li>
        <li>Filens storlek i byte vid tidpunkten för revisionen
            (Endast Subversion)</li>
        <li>Länkar att visa avviker från föregående revision eller möjligen till
            en godtycklig vald revision (om sådan finns, se ovan)</li>
        <li>Om revisionen är resultatet av en kopia, sökvägen och revisionen
            kopierad från</li>
        <li>Om revisionen föregår en kopia eller byter namn kommer sökvägen i
            tidpunkten för revideringen</li>
        <li>Och sist men inte minst, bekräftelseloggmeddelandet som ska berätta
            om orsaken till förändringen.</li>
      </ul>
    <p>
      Längst ner på sidan hittar du ett formulär som tillåter
      att begära skillnader mellan godtyckliga revisioner.
    </p>
